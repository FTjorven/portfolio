// Builds the case pages of the combined site (all/) from the two separate sites.
// Every case study is written once, in visual/ or creative/. This copies it into all/ and:
//   - switches it to the light theme (the combined site is light, like before the split)
//   - shows all four contact links
//   - points "Next project" along the combined order below
// Runs before `npm run dev:all` / `build:all`. The copies are gitignored: edit visual/ or creative/.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');

// Combined order of the case studies, with the folder each one lives in
const PAGES = [
  { file: 'thresholds.html', from: 'creative', title: 'Thresholds' },
  { file: 'myst.html', from: 'creative', title: 'Myst' },
  { file: 'soundcheck.html', from: 'creative', title: 'The Soundcheck' },
  { file: 'walter.html', from: 'visual', title: 'Designing without a name' },
  { file: 'milesmeals.html', from: 'visual', title: 'Miles &amp; Meals' },
  { file: 'revinyl.html', from: 'visual', title: 'Revinyl' },
  { file: 'houseremembers.html', from: 'visual', title: 'The House Remembers' },
];

const SOCIALS = `      <ul class="socials reveal">
        <li><a href="mailto:florintjorven@gmail.com">Email</a></li>
        <li><a href="https://www.linkedin.com/in/tjorven-florin-8a57a91aa/" target="_blank" rel="noopener">LinkedIn</a></li>
        <li><a href="https://github.com/FTjorven/" target="_blank" rel="noopener">GitHub</a></li>
        <li><a href="https://www.behance.net/tjorvenflorin1" target="_blank" rel="noopener">Behance</a></li>
      </ul>`;

// Replace exactly one match, or stop the build: a silent miss would ship a wrong page
const replaceOnce = (html, pattern, replacement, what, file) => {
  const count = (html.match(new RegExp(pattern.source, pattern.flags.replace('g', '') + 'g')) || []).length;
  if (count !== 1) throw new Error(`sync-all: expected 1 ${what} in ${file}, found ${count}`);
  return html.replace(pattern, replacement);
};

PAGES.forEach((page, i) => {
  const next = PAGES[(i + 1) % PAGES.length];
  let html = readFileSync(resolve(root, page.from, page.file), 'utf8');

  html = html.replace('data-theme="dark"', 'data-theme="light"');
  html = html.replace('<meta name="theme-color" content="#0c0c0f" />', '<meta name="theme-color" content="#f4f2ec" />');
  html = replaceOnce(html, /      <ul class="socials reveal">[\s\S]*?<\/ul>/, SOCIALS, 'contact list', page.file);
  html = replaceOnce(
    html,
    /<a href="[a-z]+\.html" class="case-next">\s*<span class="eyebrow">Next project<\/span>\s*<span class="case-next__title">[\s\S]*?<span class="accent">/,
    `<a href="${next.file}" class="case-next">\n      <span class="eyebrow">Next project</span>\n      <span class="case-next__title">${next.title} <span class="accent">`,
    '"Next project" link',
    page.file
  );
  html = html.replace('<!DOCTYPE html>', `<!DOCTYPE html>\n<!-- Generated by scripts/sync-all.mjs from ${page.from}/${page.file}: edit that file instead -->`);

  writeFileSync(resolve(root, 'all', page.file), html);
});

console.log(`sync-all: ${PAGES.length} case pages copied into all/`);
